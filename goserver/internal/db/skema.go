package db

import (
	"context"
	"fmt"
)

// BuatSkema membuat semua tabel & indeks (idempoten), mengikuti urutan
// init_db server.py: warga, keluarga, sesi, chat, pemilu, kandidat, suara,
// jabatan, pembangunan. Backfill data (NIK, keluarga) dan seed pembangunan
// dilakukan folder fitur masing-masing sesudah skema siap (lihat main.go).
func BuatSkema(ctx context.Context, s *Store) error {
	stmts := []string{
		`CREATE TABLE IF NOT EXISTS warga(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			username TEXT UNIQUE NOT NULL,
			pin_hash TEXT NOT NULL,
			salt TEXT NOT NULL,
			warna_baju TEXT NOT NULL,
			warna_kulit TEXT NOT NULL,
			topi TEXT NOT NULL,
			nomor_rumah INTEGER UNIQUE NOT NULL,
			blok INTEGER NOT NULL,
			kavling INTEGER NOT NULL,
			nik TEXT,
			keluarga_id BIGINT,
			peran TEXT,
			created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
		)`,
		`CREATE INDEX IF NOT EXISTS idx_warga_nomor ON warga(nomor_rumah)`,
		`CREATE TABLE IF NOT EXISTS keluarga(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			no_kk TEXT UNIQUE NOT NULL,
			created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
		)`,
		// Migrasi skema lama: kolom yang belum ada -> tambahkan (data utuh).
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS nik TEXT`,
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS keluarga_id BIGINT`,
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS peran TEXT`,
		// Gender: 'L'/'P', NULL = belum diisi (warga lama & pra-daftar admin).
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS gender TEXT`,
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS rupa TEXT NOT NULL DEFAULT ''`, // kustom karakter (JSON)
		`CREATE INDEX IF NOT EXISTS idx_warga_keluarga ON warga(keluarga_id)`,
		// Pemilu (26 Nov 2026): hak pilih & mencalonkan hanya untuk warga
		// TERVERIFIKASI = follower @negaramerdu (dibuat/ditandai autoreg
		// lewat token admin). Pendaftaran mandiri mulai FALSE.
		`ALTER TABLE warga ADD COLUMN IF NOT EXISTS terverifikasi BOOLEAN NOT NULL DEFAULT FALSE`,
		`CREATE TABLE IF NOT EXISTS sesi(
			token TEXT PRIMARY KEY,
			warga_id INTEGER NOT NULL,
			created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
		)`,
		`CREATE TABLE IF NOT EXISTS chat(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			warga_id INTEGER NOT NULL,
			username TEXT NOT NULL,
			isi TEXT NOT NULL,
			created_at TEXT NOT NULL,
			sistem INTEGER NOT NULL DEFAULT 0
		)`,
		`CREATE INDEX IF NOT EXISTS idx_chat_id ON chat(id)`,
		`ALTER TABLE chat ADD COLUMN IF NOT EXISTS sistem INTEGER NOT NULL DEFAULT 0`,
		`CREATE TABLE IF NOT EXISTS pemilu(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			status TEXT NOT NULL DEFAULT 'pencalonan',
			dibuka_pada TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
			ditutup_pada TEXT
		)`,
		// Saat fase pemungutan dibuka: batas hak pilih (warga terdaftar SEBELUM ini).
		`ALTER TABLE pemilu ADD COLUMN IF NOT EXISTS pemungutan_pada TEXT`,
		`CREATE TABLE IF NOT EXISTS kandidat(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			pemilu_id INTEGER NOT NULL,
			warga_id INTEGER NOT NULL,
			jabatan TEXT NOT NULL,
			wilayah INTEGER NOT NULL DEFAULT 0,
			visi TEXT NOT NULL,
			misi TEXT NOT NULL,
			dibuat_pada TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
			UNIQUE(pemilu_id, warga_id)
		)`,
		`CREATE INDEX IF NOT EXISTS idx_kandidat_pemilu ON kandidat(pemilu_id, jabatan, wilayah)`,
		`CREATE TABLE IF NOT EXISTS suara(
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			pemilu_id INTEGER NOT NULL,
			pemilih_id INTEGER NOT NULL,
			jabatan TEXT NOT NULL,
			wilayah INTEGER NOT NULL DEFAULT 0,
			kandidat_id INTEGER NOT NULL,
			dibuat_pada TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
			UNIQUE(pemilu_id, pemilih_id, jabatan, wilayah)
		)`,
		`CREATE INDEX IF NOT EXISTS idx_suara_kandidat ON suara(kandidat_id)`,
		`CREATE TABLE IF NOT EXISTS jabatan(
			warga_id BIGINT PRIMARY KEY,
			jabatan TEXT NOT NULL,
			wilayah INTEGER NOT NULL DEFAULT 0,
			sejak TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
			pemilu_id INTEGER
		)`,
		`CREATE TABLE IF NOT EXISTS pembangunan(
			kunci TEXT PRIMARY KEY,
			nama TEXT NOT NULL,
			biaya INTEGER NOT NULL,
			kol INTEGER NOT NULL,
			bar INTEGER NOT NULL,
			status TEXT NOT NULL DEFAULT 'belum',
			dibangun_pada TEXT
		)`,
	}
	for _, q := range stmts {
		if _, err := s.Pool.Exec(ctx, q); err != nil {
			return fmt.Errorf("skema: %w", err)
		}
	}
	return nil
}

// IndeksUnikNIK membuat indeks unik NIK (sesudah backfill). Kegagalan
// (NIK ganda warisan) hanya diperingatkan, sama seperti server.py.
func IndeksUnikNIK(ctx context.Context, s *Store) {
	if _, err := s.Pool.Exec(ctx, "CREATE UNIQUE INDEX IF NOT EXISTS idx_warga_nik ON warga(nik)"); err != nil {
		fmt.Println("PERINGATAN: indeks unik NIK tidak dibuat (NIK ganda?)")
	}
}
